#include<iostream>
using namespace std;

int main() {
    //bitwise AND
    cout << (3&5) << endl; // 1

    //bitwise OR 
    cout << (3|5) << endl; // 7

    //Exclusive OR (XOR) 
    cout << (3^5) << endl; // 6

    //Binary NOT operator
    cout << (~6) << endl; // -7 

    //Left shift operator
    cout << (8<<3) << endl; // 64

}